#!/usr/bin/env node
/**
 * Generates the transactional Dr. AIT catalogue seed. Correct answers remain
 * outside the frontend bundle in supabase/seed/source/.
 *
 *   node scripts/generate-seed-sql.mjs
 *
 * The generated SQL is intended for Supabase SQL Editor after migrations
 * 005–013. It does not connect to a database.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { examMeta, examQuestions } from '../supabase/seed/source/examMockData.js';
import { SUBJECT_QUESTIONS } from '../supabase/seed/source/subjectQuestionBanks.js';
import { SUBJECTS } from '../src/data/subjectCatalog.js';

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const arr = (a) => `ARRAY[${a.map(q).join(', ')}]::text[]`;
const semesterNo = (label) => Number.parseInt(label, 10) || 'NULL';
const normalize = (v) => String(v).trim().replace(/\s+/g, ' ').toLowerCase();

const subjects = [
  { code: examMeta.courseCode, title: examMeta.courseTitle, semester: examMeta.semester },
  ...SUBJECTS.map((s) => ({ code: s.code, title: s.title, semester: s.semester })),
];
const questions = [
  ...examQuestions.map((x) => ({
    code: examMeta.courseCode, topic: x.topic || 'General', difficulty: 'medium',
    statement: x.text, options: x.options, correct: x.correctOption, marks: 2,
  })),
  ...SUBJECT_QUESTIONS.map((x) => ({
    code: x.subjectCode, topic: x.topic, difficulty: String(x.difficulty).toLowerCase(),
    statement: x.statement, options: x.options, correct: x.correctOption, marks: x.marks,
  })),
];

const expectedCodes = new Set(subjects.map((s) => s.code));
if (subjects.length !== 6 || expectedCodes.size !== 6) {
  throw new Error(`Expected six unique subjects; found ${subjects.length} rows and ${expectedCodes.size} codes.`);
}
if (questions.length !== 150) throw new Error(`Expected 150 catalogue questions, found ${questions.length}.`);

const perSubject = new Map([...expectedCodes].map((code) => [code, 0]));
const normalizedQuestions = new Set();
for (const x of questions) {
  if (!perSubject.has(x.code)) throw new Error(`Question references unknown subject ${x.code}: ${x.statement}`);
  perSubject.set(x.code, perSubject.get(x.code) + 1);
  if (!Array.isArray(x.options) || x.options.length !== 4
      || new Set(x.options.map((option) => String(option).trim().toLowerCase())).size !== 4
      || !Number.isInteger(x.correct) || x.correct < 0 || x.correct > 3) {
    throw new Error(`Invalid four-option MCQ: ${x.statement}`);
  }
  const normalized = normalize(x.statement);
  if (normalizedQuestions.has(normalized)) throw new Error(`Duplicate normalized question: ${x.statement}`);
  normalizedQuestions.add(normalized);
  if (!['easy', 'medium', 'hard'].includes(x.difficulty)) throw new Error(`Invalid difficulty: ${x.difficulty}`);
  if (!Number.isFinite(Number(x.marks)) || Number(x.marks) <= 0) throw new Error(`Invalid marks: ${x.statement}`);
}
for (const [code, count] of perSubject) {
  if (count !== 25) throw new Error(`Expected 25 questions for ${code}, found ${count}.`);
}

const sourceValues = questions.map((x, index) => (
  `  (${index + 1}, ${q(x.code)}, ${q(x.topic)}, ${q(x.difficulty)}, ${q(x.statement)}, ${arr(x.options)}, ${x.correct}::smallint, ${Number(x.marks)}::numeric)`
)).join(',\n');

const subjectValues = subjects.map((s) => (
  `  (${q(s.code)}, ${q(s.title)}, ${semesterNo(s.semester)}::smallint)`
)).join(',\n');

const sql = `-- 001_drait_catalogue.sql — GENERATED by scripts/generate-seed-sql.mjs; do not edit by hand.
-- Dr. AIT catalogue: ${subjects.length} expected subjects and ${questions.length} keyed MCQs.
-- Transactional, idempotent, and safe with existing global question_no values.
BEGIN;

LOCK TABLE public.questions IN EXCLUSIVE MODE;

INSERT INTO public.institutions (code, name, short_name, email_domain)
VALUES ('1DA', 'Dr. Ambedkar Institute of Technology', 'Dr. AIT', 'drait.edu.in')
ON CONFLICT (code) DO NOTHING;

DO $seed_department$
DECLARE
  v_institution_id uuid;
  v_department_id uuid;
BEGIN
  SELECT id INTO v_institution_id
  FROM public.institutions
  WHERE code::text = '1DA';

  IF v_institution_id IS NULL THEN
    RAISE EXCEPTION 'Dr. AIT institution code 1DA was not found; seed aborted.';
  END IF;

  INSERT INTO public.departments (institution_id, code, name)
  VALUES (v_institution_id, 'CS', 'Computer Science & Engineering')
  ON CONFLICT (institution_id, code) DO NOTHING
  RETURNING id INTO v_department_id;

  IF v_department_id IS NULL THEN
    SELECT id INTO v_department_id
    FROM public.departments
    WHERE institution_id = v_institution_id AND code = 'CS';
  END IF;

  IF v_department_id IS NULL THEN
    RAISE EXCEPTION 'Could not create or reuse Dr. AIT CS department; seed aborted.';
  END IF;
END
$seed_department$;

INSERT INTO public.subjects (institution_id, department_id, code, title, semester)
SELECT i.id, d.id, v.code, v.title, v.semester
FROM public.institutions AS i
JOIN public.departments AS d ON d.institution_id = i.id AND d.code = 'CS'
CROSS JOIN (VALUES
${subjectValues}
) AS v(code, title, semester)
WHERE i.code::text = '1DA'
ON CONFLICT (institution_id, code) DO NOTHING;

CREATE TEMP TABLE seed_catalogue_questions (
  ordinal integer PRIMARY KEY,
  subject_code text NOT NULL,
  topic text NOT NULL,
  difficulty text NOT NULL,
  statement text NOT NULL,
  options text[] NOT NULL,
  correct_option smallint NOT NULL,
  marks numeric NOT NULL,
  normalized_statement text NOT NULL
) ON COMMIT DROP;

INSERT INTO pg_temp.seed_catalogue_questions
  (ordinal, subject_code, topic, difficulty, statement, options, correct_option, marks, normalized_statement)
SELECT src.ordinal, src.subject_code, src.topic, src.difficulty, src.statement,
       src.options, src.correct_option, src.marks,
       lower(regexp_replace(btrim(src.statement), E'\\\\s+', ' ', 'g'))
FROM (VALUES
${sourceValues}
) AS src(ordinal, subject_code, topic, difficulty, statement, options, correct_option, marks);

DO $seed_questions$
DECLARE
  v_institution_id uuid;
  v_subject_id uuid;
  v_question_id uuid;
  v_match_count integer;
  v_question record;
  v_existing record;
  v_next_no bigint;
  v_created integer := 0;
  v_identity_always boolean;
  v_normalized_generated boolean;
  v_columns text;
  v_values text;
  v_override text := '';
  v_insert_sql text;
  v_sequence text;
  v_sequence_last bigint;
  v_max_question_no bigint;
  v_subject_count integer;
  v_catalogue_question_count integer;
  v_answer_key_count integer;
  v_bad_subject_count integer;
  v_bad_course_count integer;
BEGIN
  SELECT id INTO v_institution_id
  FROM public.institutions
  WHERE code::text = '1DA';
  IF v_institution_id IS NULL THEN
    RAISE EXCEPTION 'Dr. AIT institution code 1DA was not found; seed aborted.';
  END IF;

  IF (SELECT count(*) FROM public.subjects WHERE institution_id = v_institution_id) < 6 THEN
    RAISE EXCEPTION 'Subject creation did not produce all six expected subjects.';
  END IF;

  SELECT a.attidentity = 'a'
  INTO v_identity_always
  FROM pg_attribute a
  WHERE a.attrelid = 'public.questions'::regclass
    AND a.attname = 'question_no'
    AND NOT a.attisdropped;

  SELECT a.attgenerated <> ''
  INTO v_normalized_generated
  FROM pg_attribute a
  WHERE a.attrelid = 'public.questions'::regclass
    AND a.attname = 'normalized_statement'
    AND NOT a.attisdropped;

  IF v_identity_always IS NULL OR v_normalized_generated IS NULL THEN
    RAISE EXCEPTION 'questions must have question_no and normalized_statement columns.';
  END IF;

  -- The table lock prevents concurrent writers from claiming the chosen range.
  SELECT COALESCE(max(question_no), 0) + 1
    INTO v_next_no
  FROM public.questions;

  FOR v_question IN
    SELECT src.*, s.id AS subject_id
    FROM pg_temp.seed_catalogue_questions AS src
    JOIN public.subjects AS s
      ON s.institution_id = v_institution_id
     AND s.code = src.subject_code
    ORDER BY src.ordinal
  LOOP
    SELECT count(*) INTO v_match_count
    FROM public.questions AS q
    WHERE q.institution_id = v_institution_id
      AND NOT q.is_archived
      AND lower(regexp_replace(btrim(q.statement), E'\\\\s+', ' ', 'g'))
          = v_question.normalized_statement;

    IF v_match_count > 1 THEN
      RAISE EXCEPTION 'Multiple live questions match normalized catalogue statement: %', v_question.statement;
    END IF;

    v_question_id := NULL;
    IF v_match_count = 1 THEN
      SELECT q.* INTO v_existing
      FROM public.questions AS q
      WHERE q.institution_id = v_institution_id
        AND NOT q.is_archived
        AND lower(regexp_replace(btrim(q.statement), E'\\\\s+', ' ', 'g'))
            = v_question.normalized_statement
      FOR UPDATE;

      IF v_existing.subject_id IS DISTINCT FROM v_question.subject_id
         OR v_existing.topic IS DISTINCT FROM v_question.topic
         OR v_existing.options IS DISTINCT FROM v_question.options
         OR v_existing.difficulty::text IS DISTINCT FROM v_question.difficulty
         OR v_existing.marks IS DISTINCT FROM v_question.marks
         OR v_existing.negative_marks IS DISTINCT FROM 0::numeric THEN
        RAISE EXCEPTION 'Existing question conflicts with catalogue data; refusing to overwrite it: %', v_question.statement;
      END IF;

      v_question_id := v_existing.id;
      IF NOT v_normalized_generated THEN
        IF v_existing.normalized_statement IS NULL THEN
          UPDATE public.questions
          SET normalized_statement = lower(regexp_replace(btrim(statement), E'\\\\s+', ' ', 'g'))
          WHERE id = v_question_id;
        ELSIF v_existing.normalized_statement IS DISTINCT FROM v_question.normalized_statement THEN
          RAISE EXCEPTION 'Existing normalized_statement disagrees with the canonical expression for question %.', v_question_id;
        END IF;
      ELSIF v_existing.normalized_statement IS DISTINCT FROM v_question.normalized_statement THEN
        RAISE EXCEPTION 'Generated normalized_statement disagrees with the canonical expression for question %.', v_question_id;
      END IF;
    ELSE
      IF v_next_no > 9223372036854775807 THEN
        RAISE EXCEPTION 'No free BIGINT question_no range remains.';
      END IF;

      v_columns := 'institution_id, subject_id, question_no, topic, statement, options, difficulty, marks, negative_marks';
      v_values := '$1, $2, $3, $4, $5, $6, $7::public.question_difficulty, $8, $9';
      IF v_identity_always THEN
        v_override := ' OVERRIDING SYSTEM VALUE';
      END IF;
      IF NOT v_normalized_generated THEN
        v_columns := v_columns || ', normalized_statement';
        v_values := v_values || ', $10';
      END IF;
      v_insert_sql := format(
        'INSERT INTO public.questions (%s)%s VALUES (%s) RETURNING id',
        v_columns, v_override, v_values
      );

      IF v_normalized_generated THEN
        EXECUTE v_insert_sql
          USING v_institution_id, v_question.subject_id, v_next_no,
                v_question.topic, v_question.statement, v_question.options,
                v_question.difficulty, v_question.marks, 0::numeric
          INTO v_question_id;
      ELSE
        EXECUTE v_insert_sql
          USING v_institution_id, v_question.subject_id, v_next_no,
                v_question.topic, v_question.statement, v_question.options,
                v_question.difficulty, v_question.marks, 0::numeric,
                v_question.normalized_statement
          INTO v_question_id;
      END IF;

      v_next_no := v_next_no + 1;
      v_created := v_created + 1;
    END IF;

    INSERT INTO public.question_answer_keys (question_id, institution_id, correct_option)
    VALUES (v_question_id, v_institution_id, v_question.correct_option)
    ON CONFLICT (question_id) DO NOTHING;

    IF NOT EXISTS (
      SELECT 1
      FROM public.question_answer_keys k
      WHERE k.question_id = v_question_id
        AND k.institution_id = v_institution_id
        AND k.correct_option = v_question.correct_option
    ) THEN
      RAISE EXCEPTION 'Question % does not have the expected answer key; seed aborted.', v_question_id;
    END IF;
  END LOOP;

  IF (SELECT count(*) FROM pg_temp.seed_catalogue_questions) <> 150 THEN
    RAISE EXCEPTION 'Expected 150 source catalogue questions.';
  END IF;

  SELECT count(*) INTO v_subject_count
  FROM public.subjects s
  WHERE s.institution_id = v_institution_id
    AND s.code IN ('22CS601', '22CS302', '22CS402', '22CS403', '22CS502', '22CS304');

  SELECT count(*) INTO v_bad_subject_count
  FROM public.subjects s
  LEFT JOIN public.departments d
    ON d.id = s.department_id
   AND d.institution_id = s.institution_id
  WHERE s.institution_id = v_institution_id
    AND s.code IN ('22CS601', '22CS302', '22CS402', '22CS403', '22CS502', '22CS304')
    -- a subject without a department is fine; one in another department is not
    AND s.department_id IS NOT NULL AND (d.id IS NULL OR d.code <> 'CS');

  SELECT count(*) INTO v_catalogue_question_count
  FROM pg_temp.seed_catalogue_questions src
  JOIN public.subjects s
    ON s.institution_id = v_institution_id AND s.code = src.subject_code
  JOIN public.questions q
    ON q.institution_id = v_institution_id
   AND q.subject_id = s.id
   AND lower(regexp_replace(btrim(q.statement), E'\\\\s+', ' ', 'g')) = src.normalized_statement;

  SELECT count(*) INTO v_answer_key_count
  FROM pg_temp.seed_catalogue_questions src
  JOIN public.subjects s
    ON s.institution_id = v_institution_id AND s.code = src.subject_code
  JOIN public.questions q
    ON q.institution_id = v_institution_id
   AND q.subject_id = s.id
   AND lower(regexp_replace(btrim(q.statement), E'\\\\s+', ' ', 'g')) = src.normalized_statement
  JOIN public.question_answer_keys k
    ON k.question_id = q.id AND k.institution_id = v_institution_id;

  SELECT count(*) INTO v_bad_course_count
  FROM (
    SELECT src.subject_code
    FROM pg_temp.seed_catalogue_questions src
    JOIN public.subjects s
      ON s.institution_id = v_institution_id AND s.code = src.subject_code
    LEFT JOIN public.questions q
      ON q.institution_id = v_institution_id
     AND q.subject_id = s.id
     AND lower(regexp_replace(btrim(q.statement), E'\\\\s+', ' ', 'g')) = src.normalized_statement
    LEFT JOIN public.question_answer_keys k
      ON k.question_id = q.id AND k.institution_id = v_institution_id
    GROUP BY src.subject_code
    HAVING count(DISTINCT q.id) <> 25 OR count(DISTINCT k.question_id) <> 25
  ) AS invalid_courses;

  IF v_subject_count <> 6
     OR v_catalogue_question_count <> 150
     OR v_answer_key_count <> 150
     OR v_bad_subject_count <> 0
     OR v_bad_course_count <> 0 THEN
    RAISE EXCEPTION
      'Catalogue assertions failed: expected subjects=6, questions=150, keys=150, subjects_without_CS=0, bad_courses=0; found %, %, %, %, %.',
      v_subject_count, v_catalogue_question_count, v_answer_key_count,
      v_bad_subject_count, v_bad_course_count;
  END IF;

  v_sequence := pg_get_serial_sequence('public.questions', 'question_no');
  IF v_sequence IS NOT NULL AND v_created > 0 THEN
    EXECUTE format('SELECT last_value FROM %s', v_sequence::regclass) INTO v_sequence_last;
    SELECT COALESCE(max(question_no), 0) INTO v_max_question_no FROM public.questions;
    PERFORM setval(v_sequence::regclass, GREATEST(v_sequence_last, v_max_question_no), true);
  END IF;
END
$seed_questions$;

COMMIT;
`;

const out = fileURLToPath(new URL('../supabase/seed/001_drait_catalogue.sql', import.meta.url));
writeFileSync(out, sql);
console.log(`Wrote ${out}: ${subjects.length} subjects, ${questions.length} questions.`);
