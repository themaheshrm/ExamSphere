#!/usr/bin/env node
/**
 * Generates supabase/seed/001_drait_catalogue.sql from the reviewed demo
 * question banks in supabase/seed/source/ (which contain correct answers and
 * therefore live outside src/ — they are never bundled into the web app).
 *
 *   node scripts/generate-seed-sql.mjs
 *
 * The generated SQL is idempotent (existing institution, subjects and
 * questions are left untouched). Review it, then run it in the Supabase SQL
 * editor AFTER migrations 005–013. This script itself touches no database.
 */
import { writeFileSync } from 'node:fs';
import { examMeta, examQuestions } from '../supabase/seed/source/examMockData.js';
import { SUBJECT_QUESTIONS } from '../supabase/seed/source/subjectQuestionBanks.js';
import { SUBJECTS } from '../src/data/subjectCatalog.js';

const q = (v) => `'${String(v).replace(/'/g, "''")}'`;
const arr = (a) => `ARRAY[${a.map(q).join(', ')}]::text[]`;
const semesterNo = (label) => Number.parseInt(label, 10) || 'NULL';

const subjects = [
  { code: examMeta.courseCode, title: examMeta.courseTitle, semester: examMeta.semester },
  ...SUBJECTS.map((s) => ({ code: s.code, title: s.title, semester: s.semester })),
];
const questions = [
  ...examQuestions.map((x) => ({ code: examMeta.courseCode, topic: x.topic || 'General', difficulty: 'medium', statement: x.text, options: x.options, correct: x.correctOption, marks: 2 })),
  ...SUBJECT_QUESTIONS.map((x) => ({ code: x.subjectCode, topic: x.topic, difficulty: String(x.difficulty).toLowerCase(), statement: x.statement, options: x.options, correct: x.correctOption, marks: x.marks })),
];
for (const x of questions) {
  if (x.options.length !== 4 || new Set(x.options).size !== 4 || !(x.correct >= 0 && x.correct <= 3)) throw new Error(`Invalid question: ${x.statement}`);
}

const sql = `-- 001_drait_catalogue.sql — GENERATED by scripts/generate-seed-sql.mjs; do not edit by hand.
-- Dr. AIT institution, CSE department, ${subjects.length} subjects and ${questions.length} keyed questions.
-- Idempotent: rows that already exist are left unchanged. Run AFTER migrations 005–013.
BEGIN;

INSERT INTO public.institutions (code, name, short_name, email_domain)
VALUES ('1DA', 'Dr. Ambedkar Institute of Technology', 'Dr. AIT', 'drait.edu.in')
ON CONFLICT (code) DO NOTHING;

INSERT INTO public.departments (institution_id, code, name)
SELECT id, 'CS', 'Computer Science & Engineering' FROM public.institutions WHERE code = '1DA'
ON CONFLICT (institution_id, code) DO NOTHING;

INSERT INTO public.subjects (institution_id, department_id, code, title, semester)
SELECT i.id, d.id, v.code, v.title, v.semester
FROM public.institutions i
JOIN public.departments d ON d.institution_id = i.id AND d.code = 'CS'
CROSS JOIN (VALUES
${subjects.map((s) => `  (${q(s.code)}, ${q(s.title)}, ${semesterNo(s.semester)}::smallint)`).join(',\n')}
) AS v(code, title, semester)
WHERE i.code = '1DA'
ON CONFLICT (institution_id, code) DO NOTHING;

WITH src(code, topic, difficulty, statement, options, correct, marks) AS (VALUES
${questions.map((x) => `  (${q(x.code)}, ${q(x.topic)}, ${q(x.difficulty)}, ${q(x.statement)}, ${arr(x.options)}, ${x.correct}::smallint, ${Number(x.marks)}::numeric)`).join(',\n')}
),
inst AS (SELECT id FROM public.institutions WHERE code = '1DA'),
ins AS (
  INSERT INTO public.questions (institution_id, subject_id, topic, statement, options, difficulty, marks)
  SELECT inst.id, s.id, src.topic, src.statement, src.options, src.difficulty::public.question_difficulty, src.marks
  FROM src CROSS JOIN inst
  JOIN public.subjects s ON s.institution_id = inst.id AND s.code = src.code
  WHERE NOT EXISTS (SELECT 1 FROM public.questions x
                    WHERE x.institution_id = inst.id AND NOT x.is_archived
                      AND x.normalized_statement = lower(regexp_replace(btrim(src.statement), '\\s+', ' ', 'g')))
  RETURNING id, institution_id, statement
)
INSERT INTO public.question_answer_keys (question_id, institution_id, correct_option)
SELECT ins.id, ins.institution_id, src.correct FROM ins JOIN src ON src.statement = ins.statement;

COMMIT;
`;
const out = new URL('../supabase/seed/001_drait_catalogue.sql', import.meta.url);
writeFileSync(out, sql);
console.log(`Wrote ${out.pathname}: ${subjects.length} subjects, ${questions.length} questions.`);
